// Write public/precache.js: every file the service worker caches, and a version that changes when
// any of them does. Run after changing files in public/:  node scripts/build-precache.mjs
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, relative, sep } from 'node:path';

export const PUBLIC = fileURLToPath(new URL('../public/', import.meta.url));
// The worker itself, its generated list, licence texts and install-dialog screenshots are not needed offline.
const SKIP = [/^sw\.js$/, /^precache\.js$/, /\.txt$/, /^icons\/screenshot-/];

function walk(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? walk(path) : [relative(PUBLIC, path).split(sep).join('/')];
  });
}

export function precacheSource() {
  const files = walk(PUBLIC).filter((file) => !SKIP.some((pattern) => pattern.test(file))).sort();
  const hash = createHash('sha256');
  for (const file of files) hash.update(`${file}\0`).update(readFileSync(join(PUBLIC, file)));
  const version = hash.digest('hex').slice(0, 12);
  return `// Generated by scripts/build-precache.mjs. Do not edit by hand.\nself.PRECACHE = ${JSON.stringify({ version, files: ['./', ...files] }, null, 2)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(PUBLIC, 'precache.js'), precacheSource());
  console.log('wrote public/precache.js');
}
